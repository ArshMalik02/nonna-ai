import { z } from "zod";

const Env = z.object({
  NODE_ENV: z.enum(["development", "test", "production"]).default("development"),
  PORT: z.coerce.number().int().default(8787),
  PUBLIC_BASE_URL: z.url().optional(),
  DATABASE_URL: z.string().default("file:./data/nonna.db"),
  LOG_LEVEL: z.enum(["debug", "info", "warn", "error"]).default("info"),

  DIAL_API_URL: z.url().default("https://api.getdial.ai"),
  DIAL_API_KEY: z.string().min(1),
  DIAL_WEBHOOK_SECRET: z.string().min(1),
  /** SMS + voice. The only number the elder texts and calls. */
  DIAL_ELDER_NUMBER: z.string().regex(/^\+[1-9]\d{6,14}$/),
  /** iMessage + voice. In the family group; places outbound task calls. */
  DIAL_FAMILY_NUMBER: z.string().regex(/^\+[1-9]\d{6,14}$/),

  /** Shared secret Dial sends to /mcp/context. Generated by `pnpm dial:connect`. */
  CONTEXT_MCP_TOKEN: z.string().min(24).optional(),
  /** How often to look for new family iMessage groups. */
  GROUP_POLL_SECONDS: z.coerce.number().int().min(10).default(60),

  /**
   * `proxy` uses the local catalog of fictional agents while Darwin is unavailable.
   * `places` finds real businesses with Google Places and books by phoning them through Dial.
   */
  DARWIN_MODE: z.enum(["live", "proxy", "places"]).default("proxy"),
  DARWIN_API_URL: z.url().default("https://api.darwin.so"),
  DARWIN_SEARCH_KEY: z.string().optional(),
  DARWIN_ACT_KEY: z.string().optional(),
  DARWIN_ACT_ENABLED: z.stringbool().default(false),
  /** Google Places API (New) key, for DARWIN_MODE=places. */
  GOOGLE_PLACES_API_KEY: z.string().optional(),
  /** Only `true` lets Nonna phone a real business in places mode. */
  PLACES_CALLS_ENABLED: z.stringbool().default(false),
  /** While calls are disabled, places mode calls this number instead (e.g. a teammate's phone). */
  DEMO_CALL_TARGET: z.preprocess(
    (v) => (v === "" ? undefined : v),
    z
      .string()
      .regex(/^\+[1-9]\d{6,14}$/)
      .optional(),
  ),

  OMB_API_URL: z.url().default("http://127.0.0.1:8899"),
  OMB_API_TOKEN: z.string().optional(),
  /** The model Nonna runs on, and the engine to fall back to when the subscription is limited. */
  NONNA_MODEL: z.string().default("claude-sonnet-5-5"),
  OMB_PRIMARY_INSTANCE: z.string().default("claude"),
  OMB_FALLBACK_INSTANCE: z.string().default("claudeApi"),
  /** Shared secret OpenMausBot sends to /mcp/tools. Generated by `pnpm omb:setup`. */
  NONNA_TOOLS_TOKEN: z.string().min(24).optional(),
});
export type Env = z.infer<typeof Env>;

/** Parse and validate env once at startup. Fails fast with a readable list of problems. */
export function loadEnv(source: NodeJS.ProcessEnv = process.env): Env {
  const parsed = Env.safeParse(source);
  if (!parsed.success) {
    throw new Error(`Invalid environment:\n${z.prettifyError(parsed.error)}`);
  }
  return parsed.data;
}
